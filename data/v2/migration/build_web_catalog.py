"""Generate apps/web-v2 catalog.v2.json + browse-index.v2.json from the W2 research index.

Mechanical projection only (no semantic decisions):
- browse-index.v2.json embeds the five generated index artifacts verbatim plus
  the W2 source commit that produced them.
- catalog.v2.json embeds every canonical place/opportunity with per-record
  source pins taken from the place-index bindings.
"""
import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
INDEX = ROOT / "data/v2/indexes/research"
WEB = ROOT / "apps/web-v2"
ARTIFACTS = ["manifest.json", "place-index.json", "topic-index.json",
             "field-provenance.json", "index-status.json"]


def read(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def encoded(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode()


def sha256(raw):
    return hashlib.sha256(raw).hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--source-commit", default=None,
                    help="W2 commit producing the index (default: current HEAD)")
    ap.add_argument("--check-only", action="store_true")
    args = ap.parse_args()

    # The source commit is the last commit that touched the research index —
    # NOT the current HEAD, so regenerating the bundle stays byte-stable while
    # unrelated work lands first.
    source_commit = args.source_commit or subprocess.check_output(
        ["git", "-C", str(ROOT), "log", "-n", "1", "--format=%H", "--",
         "data/v2/indexes/research"]).decode().strip()

    place_index = read(INDEX / "place-index.json")
    topic_index = read(INDEX / "topic-index.json")
    index_status = read(INDEX / "index-status.json")
    manifest = read(INDEX / "manifest.json")
    index_revision = manifest["index_revision"]

    bindings = {b["opportunity_id"]: b for b in place_index["opportunities"]}
    docs = {}
    for pin_path in sorted((ROOT / "data/v2/opportunities").glob("*.json")):
        doc = read(pin_path)
        docs[doc["opportunity_id"]] = doc
    if set(docs) != set(bindings):
        raise ValueError("canonical/opportunity binding set mismatch")

    catalog = {
        "schema_version": "2.1.0",
        "research_only": True,
        "forecast_available": False,
        "selected_date_recommendation_eligible": False,
        "source_index_commit_sha": source_commit,
        "source_index_revision": index_revision,
        "source_pins": {oid: {"source_commit_sha": b["source_commit_sha"],
                              "source_path": b["source_path"],
                              "source_blob_sha": b["source_blob_sha"],
                              "revision": b["revision"]}
                        for oid, b in sorted(bindings.items())},
        "places": place_index["places"],
        "opportunities": [docs[b["opportunity_id"]] for b in sorted(
            bindings.values(), key=lambda b: b["opportunity_id"])],
        "evaluations": [],
    }
    browse = {
        "source_commit_sha": source_commit,
        "manifest": manifest,
        "place_index": place_index,
        "topic_index": topic_index,
        "field_provenance": read(INDEX / "field-provenance.json"),
        "index_status": index_status,
    }

    if args.check_only:
        current = (WEB / "catalog.v2.json").read_bytes()
        print(json.dumps({"match": current == encoded(catalog)}))
        return 0
    catalog_bytes = encoded(catalog)
    browse_bytes = encoded(browse)
    (WEB / "catalog.v2.json").write_bytes(catalog_bytes)
    (WEB / "browse-index.v2.json").write_bytes(browse_bytes)
    # Regenerate the byte pins the browser verifies at load time (fail-closed).
    digests = {
        "CATALOG_SHA256": sha256(catalog_bytes),
        "BROWSE_INDEX_SHA256": sha256(browse_bytes),
    }
    (WEB / "bundle-digests.mjs").write_text(
        "// GENERATED by data/v2/migration/build_web_catalog.py — do not edit by hand.\n"
        "// Byte pins for the shipped research bundle. A mismatch means the browser\n"
        "// refuses the data (fail-closed) instead of rendering unverified research.\n"
        f"export const CATALOG_SHA256 = '{digests['CATALOG_SHA256']}';\n"
        f"export const BROWSE_INDEX_SHA256 = '{digests['BROWSE_INDEX_SHA256']}';\n",
        encoding="utf-8", newline="\n")
    print(json.dumps({"places": len(catalog["places"]),
                      "opportunities": len(catalog["opportunities"]),
                      "index_revision": index_revision[:20],
                      "catalog_bytes": (WEB / "catalog.v2.json").stat().st_size}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
